#Requires -Version 5.1
<#
.SYNOPSIS
    Generate Kestra's base64-encoded SECRET_* environment file.

.DESCRIPTION
    Kestra Open Source reads secrets from environment variables named
    SECRET_<NAME> whose values are base64 encoded. This script reads
    GEMINI_API_KEY and INTERNAL_SERVICE_TOKEN from the root `.env` first and
    falls back to `backend/.env`, then writes `kestra/.env_encoded`.

    It never prints the secret values.
#>
[CmdletBinding()]
param(
    [string]$RootEnv = "",
    [string]$BackendEnv = "",
    [string]$OutFile = ""
)

$ErrorActionPreference = "Stop"

$scriptDir = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Definition }
if (-not $scriptDir) { $scriptDir = (Resolve-Path ".\kestra").Path }

if (-not $RootEnv) { $RootEnv = Join-Path $scriptDir "..\.env" }
if (-not $BackendEnv) { $BackendEnv = Join-Path $scriptDir "..\backend\.env" }
if (-not $OutFile) { $OutFile = Join-Path $scriptDir ".env_encoded" }

function Read-DotEnv {
    param([string]$Path)

    $values = @{}
    if (-not (Test-Path -LiteralPath $Path)) {
        return $values
    }

    foreach ($line in Get-Content -LiteralPath $Path) {
        $trimmed = $line.Trim()
        if (-not $trimmed -or $trimmed.StartsWith("#")) {
            continue
        }

        $separator = $trimmed.IndexOf("=")
        if ($separator -lt 1) {
            continue
        }

        $key = $trimmed.Substring(0, $separator).Trim()
        $value = $trimmed.Substring($separator + 1).Trim()
        if ($value.Length -ge 2) {
            $quotedWithDouble = $value.StartsWith('"') -and $value.EndsWith('"')
            $quotedWithSingle = $value.StartsWith("'") -and $value.EndsWith("'")
            if ($quotedWithDouble -or $quotedWithSingle) {
                $value = $value.Substring(1, $value.Length - 2)
            }
        }

        $values[$key] = $value
    }

    return $values
}

$root = Read-DotEnv -Path $RootEnv
$backend = Read-DotEnv -Path $BackendEnv

function Get-RequiredValue {
    param([string]$Name)

    if ($root.ContainsKey($Name) -and $root[$Name]) {
        return [string]$root[$Name]
    }
    if ($backend.ContainsKey($Name) -and $backend[$Name]) {
        return [string]$backend[$Name]
    }

    throw "Missing $Name. Set it in $RootEnv or $BackendEnv before generating Kestra secrets."
}

$geminiKey = Get-RequiredValue -Name "GEMINI_API_KEY"
$internalToken = Get-RequiredValue -Name "INTERNAL_SERVICE_TOKEN"

function ConvertTo-KestraSecret {
    param([string]$Value)

    return [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($Value))
}

$lines = @(
    "# Generated by kestra/make-secrets.ps1. Do not commit this file.",
    "SECRET_GEMINI_API_KEY=$(ConvertTo-KestraSecret -Value $geminiKey)",
    "SECRET_INTERNAL_SERVICE_TOKEN=$(ConvertTo-KestraSecret -Value $internalToken)"
)

Set-Content -LiteralPath $OutFile -Value $lines -Encoding ascii
Write-Host "Wrote Kestra secrets to $OutFile"
Write-Host "Restart Kestra to load them: docker compose restart kestra"
